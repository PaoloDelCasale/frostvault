"""The whole FrostVault schema, rebuilt from scratch for v0.6 (ADR-0035).

This is the only revision. Until the Owner recreates the database for real use
it is edited in place: add or change tables here and recreate the local
database. It then freezes and ordinary linear migrations resume.

It holds the core of the model; later issues of epic #578 refine the File,
Archive Version and Job tables and add their own:

- ``owner``: the single Owner, one row by construction, with its Emergency
  Password credentials and bound OIDC Identity. There is no users table and
  nothing references a user.
- ``vault_targets``: immutable S3 targets of the installation.
- ``vaults``: one external identity (``uuid``, which also names the cloud
  namespace ``vaults/<uuid>/``), one ``lifecycle`` and an orthogonal pause.
- ``files``: one row per Vault File with its current path, Local Copy and
  explicit protection state; ``file_path_history`` keeps only closed paths
  (#587).
- ``archive_versions``: Current, the replacement in progress and superseded
  versions awaiting cleanup, referenced explicitly from the file.
- ``directory_aggregate_status`` / ``directory_aggregate_dirty``: aggregate
  invalidations written in the catalog's own transaction.
- ``jobs``: the narrow Job core; ``job_leases`` holds the hot lease apart,
  ``job_uploads`` / ``job_restores`` / ``job_storage_class_changes`` the
  per-action details, ``job_groups`` with ``restore_requests`` and
  ``cloud_purge_requests`` the request; ``scheduler_vault_turns`` the fair
  scheduler's durable Vault turns; ``job_terminal_notifications`` the
  outbox of Job outcomes not yet notified (#589).
- ``sessions``, ``oidc_login``, ``auth_backoff``: Owner Sessions (revoked as a
  whole by ``owner.session_version``), transient OIDC login state and the
  durable sign-in throttle.
- ``audit_events``: append-only history whose actor is ``owner``,
  ``emergency`` or ``system``, never a user id.
- ``notifications``, ``notification_deliveries``: the Owner's inbox and
  problems, deduplicated by a unique ``dedupe_key``, plus optional email
  deliveries (#586).
- ``upload_snapshots``, ``upload_attempts``, ``upload_receipts``,
  ``upload_multiparts``: upload proofs, the snapshot and its target stored
  once, attempts and receipts independent of the Job (#588); a Job reaches its
  snapshot through ``job_uploads.snapshot_id`` (#590).
- ``vault_operation_policies``: per-Vault automation policy;
  ``bulk_upload_admissions`` / ``bulk_upload_exclusions``: durable folder
  upload admission with a path cursor (#590).

Native types throughout: ``uuid``, ``timestamptz``, ``bytea`` digests,
``bigint`` nanosecond mtimes and ``COLLATE "C"`` textual keys.
"""
