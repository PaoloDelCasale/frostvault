"""The whole FrostVault schema, rebuilt from scratch for v0.6 (ADR-0035).

This is the only revision. Until the Owner recreates the database for real use
it is edited in place: add or change tables here and recreate the local
database. It then freezes and ordinary linear migrations resume.

It holds the core of the model; later issues of epic #578 refine the File,
Archive Version and Job tables and add their own:

- ``owner``: the single Owner, one row by construction. There is no users
  table and nothing references a user.
- ``vault_targets``: immutable S3 targets of the installation.
- ``vaults``: one external identity (``uuid``, which also names the cloud
  namespace ``vaults/<uuid>/``), one ``lifecycle`` and an orthogonal pause.
- ``files``, ``archive_versions``, ``jobs``: minimal Vault File, Archive Version
  and Job rows with explicit Current Snapshot / replacement pointers.

Native types throughout: ``uuid``, ``timestamptz``, ``bytea`` digests,
``bigint`` nanosecond mtimes and ``COLLATE "C"`` textual keys.
"""
from alembic import op


revision = "0001_baseline"
down_revision = None
branch_labels = None
depends_on = None


SCHEMA = r"""
CREATE TABLE owner (
    id smallint PRIMARY KEY DEFAULT 1,
    display_name text NOT NULL,
    password_hash text,
    session_version bigint NOT NULL DEFAULT 1,
    oidc_issuer text COLLATE "C",
    oidc_subject text COLLATE "C",
    oidc_bound_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT owner_single_row_ck CHECK (id = 1),
    CONSTRAINT owner_session_version_ck CHECK (session_version >= 1),
    CONSTRAINT owner_oidc_binding_ck CHECK (
        (oidc_issuer IS NULL AND oidc_subject IS NULL AND oidc_bound_at IS NULL)
        OR (oidc_issuer <> '' AND oidc_subject <> '' AND oidc_bound_at IS NOT NULL)
    )
);

CREATE TABLE vault_targets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider text COLLATE "C" NOT NULL,
    bucket text COLLATE "C" NOT NULL,
    region text COLLATE "C" NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT vault_targets_provider_ck CHECK (provider = 's3'),
    CONSTRAINT vault_targets_bucket_ck CHECK (bucket <> ''),
    CONSTRAINT vault_targets_region_ck CHECK (region <> ''),
    CONSTRAINT vault_targets_uq UNIQUE (provider, bucket, region)
);

CREATE FUNCTION vault_targets_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'vault_targets rows are immutable'
        USING ERRCODE = 'restrict_violation';
END
$$;

CREATE TRIGGER vault_targets_immutable
    BEFORE UPDATE OR DELETE ON vault_targets
    FOR EACH ROW EXECUTE FUNCTION vault_targets_immutable();

-- lifecycle:
--   active              protected; local and cloud work run unless paused
--   reconnect_required  local work suspended until Reconnect Folder completes
--   stopping            Stop Protection in progress; the root stays allocated
--   tombstone           Vault Tombstone; the root is released, never resumed
-- Pause is the Owner's hold on new cloud Jobs, orthogonal to reconnect.
CREATE TABLE vaults (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid uuid NOT NULL DEFAULT gen_random_uuid(),
    target_id bigint NOT NULL REFERENCES vault_targets(id) ON DELETE RESTRICT,
    name text NOT NULL,
    source_root text COLLATE "C" NOT NULL,
    root_identity_version text COLLATE "C",
    root_identity text COLLATE "C",
    reconnect_volume_fingerprint text COLLATE "C",
    lifecycle text COLLATE "C" NOT NULL DEFAULT 'active',
    paused boolean NOT NULL DEFAULT false,
    root_released_at timestamptz,
    storage_plan jsonb NOT NULL DEFAULT '{"transitions": []}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT vaults_uuid_uq UNIQUE (uuid),
    CONSTRAINT vaults_name_ck CHECK (btrim(name) <> ''),
    CONSTRAINT vaults_source_root_ck CHECK (source_root <> ''),
    CONSTRAINT vaults_root_identity_ck CHECK (
        (root_identity_version IS NULL) = (root_identity IS NULL)
    ),
    CONSTRAINT vaults_lifecycle_ck CHECK (
        lifecycle IN ('active', 'reconnect_required', 'stopping', 'tombstone')
    ),
    CONSTRAINT vaults_pause_ck CHECK (
        NOT paused OR lifecycle IN ('active', 'reconnect_required')
    ),
    CONSTRAINT vaults_root_release_ck CHECK (
        (lifecycle = 'tombstone') = (root_released_at IS NOT NULL)
    ),
    CONSTRAINT vaults_storage_plan_ck CHECK (jsonb_typeof(storage_plan) = 'object')
);

-- One allocated (not yet released) Vault per root.
CREATE UNIQUE INDEX vaults_allocated_root_uq
    ON vaults (source_root) WHERE lifecycle <> 'tombstone';

CREATE FUNCTION vaults_identity_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.uuid IS DISTINCT FROM OLD.uuid
       OR NEW.target_id IS DISTINCT FROM OLD.target_id THEN
        RAISE EXCEPTION 'a Vault keeps its namespace and target'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.lifecycle = 'tombstone' AND NEW.lifecycle <> 'tombstone' THEN
        RAISE EXCEPTION 'a Vault Tombstone never resumes'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER vaults_identity_immutable
    BEFORE UPDATE OF uuid, target_id, lifecycle ON vaults
    FOR EACH ROW EXECUTE FUNCTION vaults_identity_immutable();

-- One row per Vault File (#587 refines the Local Copy and protection state).
CREATE TABLE files (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    vault_id bigint NOT NULL REFERENCES vaults(id) ON DELETE RESTRICT,
    path text COLLATE "C" NOT NULL,
    path_since timestamptz NOT NULL,
    generation bigint NOT NULL DEFAULT 0,
    local_size bigint,
    local_mtime_ns bigint,
    local_sha256 bytea,
    current_version_id uuid,
    replacing_version_id uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT files_vault_path_uq UNIQUE (vault_id, path),
    CONSTRAINT files_vault_scope_uq UNIQUE (id, vault_id),
    CONSTRAINT files_path_ck CHECK (path <> ''),
    CONSTRAINT files_generation_ck CHECK (generation >= 0),
    CONSTRAINT files_local_size_ck CHECK (local_size >= 0),
    CONSTRAINT files_local_sha256_ck CHECK (octet_length(local_sha256) = 32),
    CONSTRAINT files_replacement_ck CHECK (replacing_version_id <> current_version_id)
);

-- An Archive Version exists only while it is Current, a replacement in
-- progress, or superseded with open cleanup: no version numbering, no purged
-- history. The row is deleted with its completed cleanup proof.
CREATE TABLE archive_versions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    file_id uuid NOT NULL REFERENCES files(id) ON DELETE RESTRICT,
    object_key text COLLATE "C" NOT NULL,
    provider_version_id text COLLATE "C",
    size bigint NOT NULL,
    plaintext_sha256 bytea,
    storage_class text COLLATE "C",
    integrity text COLLATE "C" NOT NULL DEFAULT 'unverified',
    availability text COLLATE "C" NOT NULL DEFAULT 'unknown',
    verified_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT archive_versions_file_scope_uq UNIQUE (id, file_id),
    CONSTRAINT archive_versions_object_version_uq UNIQUE (object_key, provider_version_id),
    CONSTRAINT archive_versions_object_key_ck CHECK (object_key <> ''),
    CONSTRAINT archive_versions_provider_version_ck CHECK (provider_version_id <> ''),
    CONSTRAINT archive_versions_size_ck CHECK (size >= 0),
    CONSTRAINT archive_versions_sha256_ck CHECK (octet_length(plaintext_sha256) = 32),
    CONSTRAINT archive_versions_integrity_ck CHECK (
        integrity IN ('unverified', 'verified', 'mismatch')
    ),
    CONSTRAINT archive_versions_availability_ck CHECK (
        availability IN ('unknown', 'available', 'missing')
    ),
    CONSTRAINT archive_versions_verified_ck CHECK (
        integrity <> 'verified' OR verified_at IS NOT NULL
    )
);

CREATE INDEX archive_versions_file_idx ON archive_versions (file_id);

-- The pointers name versions of this very file only.
ALTER TABLE files
    ADD CONSTRAINT files_current_version_fk
        FOREIGN KEY (current_version_id, id)
        REFERENCES archive_versions (id, file_id) ON DELETE RESTRICT,
    ADD CONSTRAINT files_replacing_version_fk
        FOREIGN KEY (replacing_version_id, id)
        REFERENCES archive_versions (id, file_id) ON DELETE RESTRICT;

-- Common narrow Job core (#589 adds lease, hot state and per-action details).
CREATE TABLE jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vault_id bigint NOT NULL,
    file_id uuid NOT NULL,
    archive_version_id uuid,
    action text COLLATE "C" NOT NULL,
    status text COLLATE "C" NOT NULL,
    origin text COLLATE "C" NOT NULL,
    group_id uuid,
    total_bytes bigint NOT NULL DEFAULT 0,
    transferred_bytes bigint NOT NULL DEFAULT 0,
    message text,
    requested_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    CONSTRAINT jobs_file_fk FOREIGN KEY (file_id, vault_id)
        REFERENCES files (id, vault_id) ON DELETE RESTRICT,
    CONSTRAINT jobs_archive_version_fk FOREIGN KEY (archive_version_id, file_id)
        REFERENCES archive_versions (id, file_id) ON DELETE RESTRICT,
    CONSTRAINT jobs_action_ck CHECK (
        action IN ('upload', 'recover', 'free-space', 'rename', 'cloud-purge', 'storage-class')
    ),
    CONSTRAINT jobs_origin_ck CHECK (origin IN ('manual', 'automatic')),
    CONSTRAINT jobs_bytes_ck CHECK (total_bytes >= 0 AND transferred_bytes >= 0)
);

CREATE INDEX jobs_file_idx ON jobs (file_id);
CREATE INDEX jobs_vault_status_idx ON jobs (vault_id, status);
"""


def upgrade() -> None:
    op.execute(SCHEMA)


